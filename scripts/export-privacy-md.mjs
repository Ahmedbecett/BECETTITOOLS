#!/usr/bin/env node
/**
 * Mirrors the published privacy policy (scripts/site/i18n/privacy.mjs) into
 * docs/PUBLIC_PRIVACY_POLICY.md, so the repository copy and the website cannot drift.
 *
 *   node scripts/export-privacy-md.mjs
 */

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { privacy } from "./site/i18n/privacy.mjs";
import { locales, pages } from "./site/i18n/pages.mjs";
import { app, contact, repository } from "./site/site.config.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const out = path.join(repoRoot, "docs", "PUBLIC_PRIVACY_POLICY.md");

const LANG_NAME = { en: "English", fr: "Français", ar: "العربية" };

function localeSection(loc) {
  const p = privacy[loc];
  const t = pages[loc];
  const url = `${pages[loc].route.privacy}`;
  const lines = [];
  lines.push(`## ${LANG_NAME[loc]} (${loc})`);
  lines.push("");
  lines.push(`**${p.heading}** — ${app.name} ${app.versionName}`);
  lines.push("");
  lines.push(`- ${p.appLine}`);
  lines.push(`- ${p.effective} · ${p.updated}`);
  lines.push(`- Published page: \`/${url}\``);
  lines.push("");
  lines.push(`**${p.summaryTitle}.** ${p.summary}`);
  lines.push("");
  for (const s of p.sections) {
    lines.push(`### ${s.heading}`);
    lines.push("");
    for (const para of s.paragraphs || []) lines.push(para, "");
    if (s.list) {
      for (const item of s.list) lines.push(`- ${item}`);
      lines.push("");
    }
    for (const para of s.after || []) lines.push(para, "");
  }
  lines.push(`**${t.contact.title}** — ${contact.email} · ${repository.issuesUrl}`);
  lines.push("");
  lines.push(`> ${p.disclaimer}`);
  lines.push("");
  return lines.join("\n");
}

const header = `# Public privacy policy — ${app.name} (${app.packageName}) v${app.versionName}

<!-- Generated by scripts/export-privacy-md.mjs — edit scripts/site/i18n/privacy.mjs instead. -->

This is the repository mirror of the privacy policy published with the landing page in
English, French and Arabic. The published pages under \`website/privacy/\` are the canonical
version; this file exists so the policy can be read and reviewed without deploying anything.

- App: ${app.name} ${app.versionName} (\`${app.packageName}\`, install id \`${app.debugPackageName}\`)
- Platform: ${app.minAndroidLabel}+ · build type: ${app.buildType}
- Effective: 6 November 2026
- Contact: ${contact.email}
- Source of truth: \`scripts/site/i18n/privacy.mjs\`

---

`;

const body = locales.map(localeSection).join("\n---\n\n");

await writeFile(out, header + body, "utf8");
console.log(`Wrote ${path.relative(repoRoot, out)} (${locales.length} languages, ${(header + body).length} bytes)`);
