#!/usr/bin/env node
/**
 * Builds the deployable static site into website/.
 *
 *   node scripts/build-site.mjs
 *   node scripts/build-site.mjs --base-url=https://becetti-tools.vercel.app
 *   node scripts/build-site.mjs --base-url=https://ahmedbecett.github.io --base-path=/BECETTITOOLS
 *   SITE_BASE_URL=... SITE_BASE_PATH=... node scripts/build-site.mjs
 *
 * Only the canonical/hreflang/sitemap URLs depend on --base-url/--base-path;
 * every internal link and asset reference is relative, so the same output works
 * at a domain root or in a sub-directory without any other change.
 */

import { mkdir, writeFile, copyFile, readdir, stat } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { normaliseBase, app, apk } from "./site/site.config.mjs";
import { locales, pages } from "./site/i18n/pages.mjs";
import { renderPreview, previews } from "./site/previews.mjs";
import {
  createUrls,
  renderLanding,
  renderPrivacy,
  renderRootRedirect,
  render404,
  renderSitemap,
  renderRobots,
  renderManifest,
  renderVercelConfig,
  BUILD_DATE,
} from "./site/render.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const staticDir = path.join(here, "site", "static");

function parseArgs(argv) {
  const out = {};
  for (const arg of argv.slice(2)) {
    const m = /^--([^=]+)=(.*)$/.exec(arg);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

const args = parseArgs(process.argv);
const base = normaliseBase({
  baseUrl: args["base-url"] || process.env.SITE_BASE_URL,
  basePath: args["base-path"] ?? process.env.SITE_BASE_PATH,
});
const outDir = path.resolve(repoRoot, args.out || "website");

const urls = createUrls({ base: base.base });
const written = [];

async function emit(relPath, contents) {
  const full = path.join(outDir, relPath);
  await mkdir(path.dirname(full), { recursive: true });
  await writeFile(full, contents, "utf8");
  written.push(relPath);
}

async function copyAsset(srcName, relDest) {
  const src = path.join(staticDir, srcName);
  const dest = path.join(outDir, relDest);
  await mkdir(path.dirname(dest), { recursive: true });
  await copyFile(src, dest);
  written.push(relDest);
}

async function main() {
  // Pages
  for (const loc of locales) {
    await emit(`${urls.landingPath(loc)}index.html`, renderLanding({ urls, loc }));
    await emit(`${urls.privacyPath(loc)}index.html`, renderPrivacy({ urls, loc }));
  }

  // Root + fallbacks
  await emit("index.html", renderRootRedirect({ urls }));
  await emit("404.html", render404({ urls, t: pages.en }));

  // Technical SEO files
  await emit("robots.txt", renderRobots({ urls }));
  await emit("sitemap.xml", renderSitemap({ urls }));
  await emit("site.webmanifest", renderManifest({ urls }));
  await emit("vercel.json", renderVercelConfig());

  // Styles, behaviour, brand assets
  await copyAsset("site.css", "assets/css/site.css");
  await copyAsset("site.js", "assets/js/site.js");
  await copyAsset("logo.svg", "assets/img/logo.svg");
  await copyAsset("favicon.svg", "assets/img/favicon.svg");

  // Monetag service worker, served from the site root so its scope covers the whole origin.
  // The file is byte-identical to what the network dashboard hands out — do not edit it here;
  // see docs/ADS_SITE.md for what it does and what must be disclosed before it is registered.
  await copyAsset("sw.js", "sw.js");

  // Illustrative UI previews
  for (const id of Object.keys(previews)) {
    await emit(`assets/img/previews/${id}.svg`, renderPreview(id));
  }

  // Raster assets are generated by scripts/make-images.sh (ImageMagick) and committed.
  const requiredRaster = [
    "assets/img/logo-192.png",
    "assets/img/logo-512.png",
    "assets/img/favicon-32.png",
    "assets/img/apple-touch-icon.png",
    "assets/img/og-image.png",
  ];
  const missing = requiredRaster.filter((p) => !existsSync(path.join(outDir, p)));
  if (missing.length) {
    console.warn(
      `\n⚠ Missing raster assets (run scripts/make-images.sh):\n  - ${missing.join("\n  - ")}\n`
    );
  }

  // Guard: the APK must never be copied into the site output.
  const apkInSite = (await readdir(outDir, { recursive: true })).filter((f) => /\.(apk|aab)$/i.test(f));
  if (apkInSite.length) {
    throw new Error(`Refusing to ship binaries in the site: ${apkInSite.join(", ")}`);
  }

  const size = (await Promise.all(
    written.map(async (f) => (await stat(path.join(outDir, f))).size)
  )).reduce((a, b) => a + b, 0);

  console.log(`BECETTI TOOLS — static site built`);
  console.log(`  output      : ${path.relative(repoRoot, outDir)}/`);
  console.log(`  base URL    : ${base.base}/`);
  console.log(`  locales     : ${locales.join(", ")}`);
  console.log(`  files       : ${written.length} written, ${(size / 1024).toFixed(1)} KiB of HTML/CSS/JS/SVG`);
  console.log(`  APK         : ${apk.fileName} (${apk.mib}) — linked, not bundled`);
  console.log(`  version     : ${app.versionName} (versionCode ${app.versionCode}), ${app.buildType} build`);
  console.log(`  built on    : ${BUILD_DATE}`);
  if (missing.length) console.log(`  pending     : ${missing.length} raster asset(s)`);
}

main().catch((err) => {
  console.error("Build failed:", err);
  process.exit(1);
});
